// Document chunks table - enhanced for advanced processing
export const documentChunks = pgTable("document_chunks", {
  id: serial("id").primaryKey(),
  pdfId: integer("pdf_id").references(() => pdfs.id, { onDelete: 'cascade' }).notNull(),
  projectId: integer("project_id").references(() => projects.id, { onDelete: 'cascade' }).notNull(),
  chunkIndex: integer("chunk_index").notNull(),
  content: text("content").notNull(), // Text content of the chunk (500-1000 tokens)
  embedding: jsonb("embedding"), // Vector representation for semantic search
  pageRange: text("page_range"), // Page range (e.g. "5-7")
  topic: text("topic"), // Keywords/topic of the chunk
  tokenCount: integer("token_count"), // Number of tokens in the chunk
  overlap: text("overlap"), // Part overlapping with the previous chunk
  keywords: jsonb("keywords"), // Extracted keywords
  summary: text("summary"), // Short summary of the chunk
  contextType: text("context_type").default("general"), // kapitola, sekce, tabulka, seznam
  confidence: integer("confidence").default(100), // Confidence in the split being correct (0-100)
  createdAt: timestamp("created_at").defaultNow().notNull(),
  processedAt: timestamp("processed_at").defaultNow().notNull(),
});

