// Create insert schemas with Zod validation
export const insertUserSchema = createInsertSchema(users)
  .extend({
    email: z.string().email({ message: 'Please enter a valid email address' }),
    password: z.string().min(6, { message: 'The password must be at least 6 characters long' }),
    captchaToken: z.string().min(1, { message: 'Please confirm that you are not a robot' }).optional(),
  })
  .omit({ 
    id: true, 
    createdAt: true, 
    lastLogin: true, 
    // isActive removed from omit so it can be set explicitly during registration
    activationToken: true,
    resetPasswordToken: true,
    resetPasswordExpires: true
  });

