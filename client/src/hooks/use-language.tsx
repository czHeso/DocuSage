const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

/** English is the default language of the application. */
const DEFAULT_LANGUAGE: Language = 'en';

const STORAGE_KEY = 'docusage.language';

/** Reads the language the user picked last time, falling back to the default. */
function readStoredLanguage(): Language {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE;

  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'cs' || stored === 'en') return stored;
  } catch {
    // localStorage can be unavailable (private mode, blocked cookies)
  }

  return DEFAULT_LANGUAGE;
}

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(readStoredLanguage);

  // Remember the choice so it survives a page reload.
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Not being able to persist the choice must not break the switch itself
    }
  };

  const t = (key: string, params?: Record<string, any>): string => {
    // Fall back to English before falling back to the raw key, so a string
    // missing from one dictionary still renders as readable text.
    let translation =
      translations[language][key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;

    // Simple parameter interpolation
    if (params) {
      Object.keys(params).forEach(paramKey => {
        translation = translation.replace(new RegExp(`{${paramKey}}`, 'g'), params[paramKey]);
      });
    }

    return translation;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};